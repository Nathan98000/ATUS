/**
 * Header handling in both directions (ADR-011 steps 3.3 and 7, "Proxy chain
 * and client-IP trust"): a fresh, allowlisted upstream header set, the client
 * IP taken only from CF-Connecting-IP, forged headers dropped, origin headers
 * stripped, and the security headers on every /api response.
 */

import { beforeEach, describe, expect, it } from 'vitest'
import {
  EDGE_SECRET,
  apiJson,
  callWorker,
  expectSecurityHeaders,
  mockOrigin,
  resetEdgeState,
} from './helpers'

beforeEach(resetEdgeState)

/** Headers a client might send to impersonate the edge or spoof its address. */
const FORGED: Record<string, string> = {
  'X-ATUS-Client-IP': '198.51.100.99',
  'X-ATUS-Edge-Auth': 'forged-secret',
  'X-ATUS-Anything': 'x',
  'X-Forwarded-For': '198.51.100.1, 198.51.100.2',
  'X-Forwarded-Proto': 'http',
  'X-Forwarded-Host': 'evil.example',
  Forwarded: 'for=198.51.100.3;proto=http',
  'X-Real-IP': '198.51.100.4',
  'True-Client-IP': '198.51.100.5',
  Cookie: 'session=stolen',
  Authorization: 'Bearer stolen',
  'X-Request-ID': 'client-chosen-id',
  Origin: 'https://evil.example',
  Referer: 'https://evil.example/page',
  'User-Agent': 'curl/8.0',
  Host: 'atus-api-xyz.onrender.com',
}

describe('upstream request headers', () => {
  it('use the fake test secret, never one from the environment', () => {
    expect(EDGE_SECRET).toBe('test-edge-secret-0123456789abcdef')
  })

  it('are exactly the allowlisted set, with the client IP from CF-Connecting-IP', async () => {
    const calls = mockOrigin(() => apiJson('{}'))
    await callWorker('/api/v1/analysis/estimate', {
      method: 'POST',
      headers: {
        ...FORGED,
        'CF-Connecting-IP': '203.0.113.7',
        'Content-Type': 'application/json',
        Accept: 'application/json',
        'Accept-Encoding': 'gzip, br',
        'If-None-Match': '"abc"',
      },
      body: '{"analysis":"estimate"}',
    })
    expect(calls).toHaveLength(1)
    const sent = Object.fromEntries(calls[0]!.headers)
    expect(Object.keys(sent).sort()).toEqual([
      'accept',
      'accept-encoding',
      'content-type',
      'if-none-match',
      'user-agent',
      'x-atus-client-ip',
      'x-atus-edge-auth',
      'x-request-id',
    ])
    expect(sent['x-atus-client-ip']).toBe('203.0.113.7')
    expect(sent['x-atus-edge-auth']).toBe(EDGE_SECRET)
    expect(sent['user-agent']).toBe('atus-edge/0.1.0')
    expect(sent['content-type']).toBe('application/json')
    expect(sent['accept']).toBe('application/json')
    expect(sent['accept-encoding']).toBe('gzip, br')
    expect(sent['if-none-match']).toBe('"abc"')
    // Generated by the Worker, in the form the API accepts from the edge.
    expect(sent['x-request-id']).toMatch(/^[A-Za-z0-9._-]{8,64}$/)
    expect(sent['x-request-id']).not.toBe('client-chosen-id')
  })

  it('carry an IPv6 client address unchanged', async () => {
    const calls = mockOrigin(() => apiJson('{}'))
    await callWorker('/api/v1/meta', { headers: { 'CF-Connecting-IP': '2001:db8::1' } })
    expect(calls[0]!.headers.get('x-atus-client-ip')).toBe('2001:db8::1')
  })

  it('omit the client IP when CF-Connecting-IP is absent, even if X-ATUS-Client-IP is forged', async () => {
    const calls = mockOrigin(() => apiJson('{}'))
    await callWorker('/api/v1/meta', { headers: FORGED })
    const headers = calls[0]!.headers
    expect(headers.get('x-atus-client-ip')).toBeNull()
    expect(headers.get('x-atus-edge-auth')).toBe(EDGE_SECRET)
    // Set by the Worker itself, never copied from the client.
    const replaced = ['X-ATUS-Edge-Auth', 'User-Agent', 'X-Request-ID']
    for (const name of Object.keys(FORGED)) {
      if (replaced.includes(name)) expect(headers.get(name), name).not.toBe(FORGED[name])
      else expect(headers.get(name), name).toBeNull()
    }
  })

  it.each([
    'not-an-ip',
    '203.0.113.7, 198.51.100.1',
    '203.0.113.7\r\nX-Evil: 1',
    'x'.repeat(46),
  ])('omit a malformed CF-Connecting-IP (%j)', async (value) => {
    const calls = mockOrigin(() => apiJson('{}'))
    let request: Request
    try {
      request = new Request('https://atus.example.workers.dev/api/v1/meta', {
        headers: { 'CF-Connecting-IP': value },
      })
    } catch {
      return // The runtime refuses header values with CR/LF outright.
    }
    await callWorker(request)
    expect(calls[0]!.headers.get('x-atus-client-ip')).toBeNull()
  })

  it('send no Content-Type on GETs and never follow redirects', async () => {
    const calls = mockOrigin(() => apiJson('{}'))
    await callWorker('/api/v1/meta', { headers: { 'Content-Type': 'application/json' } })
    expect(calls[0]!.headers.get('content-type')).toBeNull()
    expect(calls[0]!.init.redirect).toBe('manual')
  })

  it('use a fresh request ID per request', async () => {
    const calls = mockOrigin(() => apiJson('{}'))
    await callWorker('/api/v1/meta')
    await callWorker('/api/v1/meta')
    expect(calls[0]!.headers.get('x-request-id')).not.toBe(
      calls[1]!.headers.get('x-request-id'),
    )
  })
})

describe('response headers', () => {
  it('relay the API headers, strip the origin platform headers and add security headers', async () => {
    mockOrigin(() =>
      apiJson('{"ok":true}', 200, {
        'x-request-id': 'origin-req-0042',
        'x-data-version': '2025:serving-1:abc',
        'x-analytics-version': '0.2',
        'x-analysis-key': 'k-123',
        'x-cache': 'miss',
        'x-response-format': '1',
        'server-timing': 'db;dur=12.5, app;dur=3.1',
        etag: '"v1"',
        server: 'uvicorn',
        'x-render-origin-server': 'uvicorn',
        'x-render-routing': 'dynamic',
        'rndr-id': 'abc-123',
        'set-cookie': 'a=b; Path=/',
        'access-control-allow-origin': '*',
        'cache-control': 'public, max-age=300',
        'cf-ray': '0123456789abcdef-IAD',
        'x-powered-by': 'something',
        'content-security-policy': 'default-src *',
      }),
    )
    const response = await callWorker('/api/v1/meta')
    expect(response.headers.get('x-request-id')).toBe('origin-req-0042')
    expect(response.headers.get('x-data-version')).toBe('2025:serving-1:abc')
    expect(response.headers.get('x-analytics-version')).toBe('0.2')
    expect(response.headers.get('x-analysis-key')).toBe('k-123')
    expect(response.headers.get('x-cache')).toBe('miss')
    expect(response.headers.get('x-response-format')).toBe('1')
    expect(response.headers.get('server-timing')).toBe('db;dur=12.5, app;dur=3.1')
    expect(response.headers.get('etag')).toBe('"v1"')
    for (const name of [
      'server',
      'x-render-origin-server',
      'x-render-routing',
      'rndr-id',
      'set-cookie',
      'access-control-allow-origin',
      'cf-ray',
      'x-powered-by',
    ]) {
      expect(response.headers.get(name), name).toBeNull()
    }
    // The edge's values win over the origin's.
    expectSecurityHeaders(response)
  })

  it('carry the edge request ID when the origin sends none', async () => {
    const calls = mockOrigin(
      () => new Response('{}', { headers: { 'content-type': 'application/json' } }),
    )
    const response = await callWorker('/api/v1/meta')
    expect(response.headers.get('x-request-id')).toBe(calls[0]!.headers.get('x-request-id'))
  })

  it('are secured on every kind of /api response', async () => {
    mockOrigin((call) => {
      if (call.url.endsWith('/hibernate')) return new Response('', { status: 503 })
      return apiJson('{"error":{"code":"x","message":"y","details":null}}', 422)
    })
    const responses = [
      await callWorker('/api/v1/meta'), // pass-through error envelope
      await callWorker('/api/nope'), // 404
      await callWorker('/api/v1/meta', { method: 'POST', body: '{}' }), // 405
      await callWorker('/api/v1/analysis/trend', { method: 'POST', body: 'x' }), // 415
      await callWorker('/api/_edge/health'),
      await callWorker('/api/v1/meta', undefined, { RENDER_ORIGIN: '' }), // 502
    ]
    for (const response of responses) expectSecurityHeaders(response)
  })
})
